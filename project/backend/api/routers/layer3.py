@router.get("/summary")
async def get_layer3_summary():
    """Get Layer 3 dashboard summary with attack targets."""
    reader = get_layer3_reader()

    if reader is None:
        # Return mock data when Layer 3 module not available
        summary = {
            'status': 'idle',
            'total_attackers': 0,
            'total_signatures': 0,
            'packet_ring_fill': 0.0,
            'attack_targets': []
        }
    else:
        summary = reader.get_layer3_summary()
        # Add total_signatures field expected by dashboard
        # (reader returns dynamic_signatures.total, dashboard expects total_signatures)
        if 'dynamic_signatures' in summary:
            summary['total_signatures'] = summary['dynamic_signatures'].get('total', 0)

    # Add attack targets from per-IP anomaly data
    service = get_dpdk_service()
    per_ip_anomaly_data = service.get_per_ip_anomaly()

    attack_targets = []
    for ip_str, state in per_ip_anomaly_data.items():
        if state.get('anomaly_active', False):
            attack_targets.append({
                'ip': ip_str,
                'level': state.get('level', 0),
                'level_name': ANOMALY_LEVEL_NAMES.get(state.get('level', 0), 'UNKNOWN'),
                'protocol': state.get('anomaly_protocol_name', 'ALL'),
                'attack_type': state.get('attack_type_name', 'UNKNOWN'),
                'dst_port': state.get('anomaly_dst_port', 0),
                'z_score': round(state.get('max_z_score', 0.0), 2),
                'tier_agreement': state.get('tier_agreement', 0),
            })

    # Sort by severity level descending
    attack_targets.sort(key=lambda x: -x['level'])
    summary['attack_targets'] = attack_targets

    # Set status to active if any targets under attack
    if attack_targets:
        summary['status'] = 'active'

    return summary


