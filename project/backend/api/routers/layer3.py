@router.post("/signatures/generate")
async def generate_signatures():
    """Auto-generate dynamic signatures for current attacks."""
    writer = get_layer3_writer()
    if writer is None:
        raise HTTPException(status_code=503, detail='Layer 3 module not available')

    service = get_dpdk_service()
    per_ip_anomaly_data = service.get_per_ip_anomaly()

    generated = []

    for ip_str, state in per_ip_anomaly_data.items():
        anomaly_active = state.get('anomaly_active', False)
        level = state.get('level', 0)

        if anomaly_active and level >= 2:  # MEDIUM or higher
            attack_target = {
                'ip': ip_str,
                'protocol': state.get('anomaly_protocol_name', 'ALL'),
                'attack_type': state.get('attack_type_name', 'UNKNOWN'),
                'dst_port': state.get('anomaly_dst_port', 0),
                'level': level,
            }

            sig_def = generate_attack_signature(attack_target)
            if sig_def:
                sig_id = writer.add_signature(sig_def)
                if sig_id > 0:
                    generated.append({
                        'id': sig_id,
                        'target': ip_str,
                        'attack_type': attack_target['attack_type'],
                        'protocol': attack_target['protocol'],
                    })

    return {
        'generated': len(generated),
        'signatures': generated,
    }


class SignatureDefinition(BaseModel):
    name: str
    protocol: str
    pattern: Optional[str] = None
    src_ip: Optional[str] = None
    dst_ip: Optional[str] = None
    src_port: Optional[int] = None
    dst_port: Optional[int] = None
    action: str = 'drop'


@router.post("/signatures/add")
async def add_signature(sig: SignatureDefinition):
    """Manually add a dynamic signature."""
    writer = get_layer3_writer()
    if writer is None:
        raise HTTPException(status_code=503, detail='Layer 3 module not available')

    sig_id = writer.add_signature(sig.model_dump())

    if sig_id < 0:
        raise HTTPException(status_code=500, detail='Failed to add signature')

    return {'id': sig_id, 'status': 'created'}


@router.delete("/signatures/{sig_id}")
async def delete_signature(sig_id: int):
    """Remove a dynamic signature."""
    writer = get_layer3_writer()
    if writer is None:
        raise HTTPException(status_code=503, detail='Layer 3 module not available')

    if writer.remove_signature(sig_id):
        return {'status': 'removed', 'id': sig_id}
    else:
        raise HTTPException(status_code=404, detail=f'Signature {sig_id} not found')


@router.post("/signatures/{sig_id}/enable")
async def enable_signature(sig_id: int):
    """Enable a dynamic signature."""
    writer = get_layer3_writer()
    if writer is None:
        raise HTTPException(status_code=503, detail='Layer 3 module not available')

    if writer.set_signature_enabled(sig_id, True):
        return {'status': 'enabled', 'id': sig_id}
    else:
        raise HTTPException(status_code=404, detail=f'Signature {sig_id} not found')


@router.post("/signatures/{sig_id}/disable")
async def disable_signature(sig_id: int):
    """Disable a dynamic signature."""
    writer = get_layer3_writer()
    if writer is None:
        raise HTTPException(status_code=503, detail='Layer 3 module not available')

    if writer.set_signature_enabled(sig_id, False):
        return {'status': 'disabled', 'id': sig_id}
    else:
        raise HTTPException(status_code=404, detail=f'Signature {sig_id} not found')
